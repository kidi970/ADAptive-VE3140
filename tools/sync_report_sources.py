#!/usr/bin/env python3
"""Keep the report's current code appendix identical to executable sources."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

REPO = Path(__file__).resolve().parents[1]
TARGET = REPO / 'docs/code/current'


def sources():
    paths = [REPO / 'Code/itrs.gpr', REPO / 'alire.toml',
             REPO / 'patches/ada-drivers-2026-10-23.patch', REPO / 'proof/lamps.gpr']
    for directory in ('Code/src', 'Code/diagnostics', 'Code/bench'):
        paths.extend(p for p in (REPO / directory).iterdir()
                     if p.suffix in ('.adb', '.ads', '.gpr'))
    return {p.relative_to(REPO).as_posix(): p.read_bytes() for p in sorted(paths)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = sources()
    source_count = len(files)
    manifest = json.dumps({name: hashlib.sha256(data).hexdigest()
                           for name, data in files.items()}, indent=2, sort_keys=True) + '\n'
    files['SHA256.json'] = manifest.encode()
    listing_names = ['Code/src/main.adb'] + sorted(
        name for name in files if name.startswith('Code/src/') and not name.endswith('/main.adb'))
    files['appendix.tex'] = ('% Generated by tools/sync_report_sources.py\n' + ''.join(
        '\\subsection*{\\texttt{' + name.split('/')[-1].replace('_', r'\_') + '}}\n'
        '\\lstinputlisting{code/current/' + name + '}\n' for name in listing_names)).encode()
    if args.check:
        actual = {p.relative_to(TARGET).as_posix(): p.read_bytes()
                  for p in TARGET.rglob('*') if p.is_file()}
        if actual != files:
            raise SystemExit('Report code is stale; run python3 tools/sync_report_sources.py')
        print(f'PASS report sources: {source_count} byte-identical files')
    else:
        if TARGET.exists():
            shutil.rmtree(TARGET)
        for name, data in files.items():
            dest = TARGET / name
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
        print(f'Synchronized {source_count} report source files')


if __name__ == '__main__':
    main()
